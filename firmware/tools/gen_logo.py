#!/usr/bin/env python3
"""Generate main/ui/img_logo.c (LVGL 9 A8 images of the VanDeck wordmark) from a PNG render.

Usage: tools/gen_logo.py path/to/logo-dark.png

The input is the logo rendered light (#ECEDEE) on the app background (#121314), e.g. the 1120x480
export of assets/vandeck-logo.svg. Brightness maps linearly to coverage, giving an alpha-only (A8)
image the firmware tints with image_recolor. Needs only macOS `sips` and the Python standard library.
"""
import os, struct, subprocess, sys, tempfile

BG, FG = 0x13, 0xED                      # green channel of #121314 / #ECEDEE
SIZES = {"img_logo_640": 640, "img_logo_160": 160}


def load_coverage(path):
    with tempfile.TemporaryDirectory() as d:
        bmp = os.path.join(d, "l.bmp")
        subprocess.run(["sips", "-s", "format", "bmp", path, "--out", bmp], check=True, capture_output=True)
        b = open(bmp, "rb").read()
    off = struct.unpack_from("<I", b, 10)[0]
    w, h = struct.unpack_from("<ii", b, 18)
    bypp = struct.unpack_from("<H", b, 28)[0] // 8
    stride = (w * bypp + 3) & ~3
    top_down = h < 0
    h = abs(h)
    cov = []
    for y in range(h):
        row = off + (y if top_down else h - 1 - y) * stride
        line = []
        for x in range(w):
            p = b[row + x * bypp: row + x * bypp + bypp]
            a = p[3] if bypp == 4 else 255
            g = p[1]
            v = 0.0 if a < 255 else min(1.0, max(0.0, (g - BG) / (FG - BG)))
            line.append(v)
        cov.append(line)
    return cov, w, h


def crop(cov, w, h, thr=0.02):
    ys = [y for y in range(h) if max(cov[y]) > thr]
    xs = [x for x in range(w) if any(cov[y][x] > thr for y in ys)]
    x0, x1, y0, y1 = xs[0], xs[-1] + 1, ys[0], ys[-1] + 1
    return [r[x0:x1] for r in cov[y0:y1]], x1 - x0, y1 - y0


def resize(cov, w, h, nw):
    """Area-average downscale to width nw (keeps aspect)."""
    nh = max(1, round(h * nw / w))
    sx, sy = w / nw, h / nh
    out = []
    for j in range(nh):
        y0, y1 = j * sy, (j + 1) * sy
        row = []
        for i in range(nw):
            x0, x1 = i * sx, (i + 1) * sx
            acc = area = 0.0
            for y in range(int(y0), min(h, int(y1 + 0.999))):
                wy = min(y + 1, y1) - max(y, y0)
                if wy <= 0:
                    continue
                for x in range(int(x0), min(w, int(x1 + 0.999))):
                    wx = min(x + 1, x1) - max(x, x0)
                    if wx > 0:
                        acc += cov[y][x] * wx * wy
                        area += wx * wy
            row.append(round(255 * acc / area) if area else 0)
        out.append(row)
    return out, nw, nh


def emit(name, img, w, h):
    data = ",".join(str(v) for r in img for v in r)
    return (f"static const uint8_t {name}_map[] = {{{data}}};\n"
            f"const lv_image_dsc_t {name} = {{\n"
            f"    .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = {w}, .h = {h}, .stride = {w} }},\n"
            f"    .data_size = sizeof({name}_map),\n"
            f"    .data = {name}_map,\n}};\n\n")


def main():
    cov, w, h = crop(*load_coverage(sys.argv[1]))
    out = ["// Generated by tools/gen_logo.py from the VanDeck wordmark render. Do not edit.\n",
           '#include "lvgl.h"\n\n']
    for name, nw in SIZES.items():
        img, iw, ih = resize(cov, w, h, nw)
        out.append(emit(name, img, iw, ih))
        print(f"{name}: {iw}x{ih}")
    dst = os.path.join(os.path.dirname(__file__), "..", "main", "ui", "img_logo.c")
    open(dst, "w").write("".join(out))


if __name__ == "__main__":
    main()
